SAMPLES = Path(__file__).resolve().parent.parent / "data" / "samples"


def _load(name):
    return json.loads((SAMPLES / name).read_text(encoding="utf-8"))


@pytest.fixture(scope="module")
def pg_factory():
    from database.audit_logger import get_connection
    from database.init_anomaly_tables import create_tables

    schema = f"ssca_test_{uuid.uuid4().hex[:8]}"

    def factory():
        conn = get_connection()
        conn.execute(f"SET search_path TO {schema}")
        return conn

    factory.schema = schema

    with get_connection() as conn:
        conn.execute(f"CREATE SCHEMA {schema}")
        real_table_exists = conn.execute(
            "SELECT to_regclass('public.verification_records') IS NOT NULL"
        ).fetchone()[0]

    # An EMPTY copy of verification_records inside the test schema.
    with factory() as conn:
        if real_table_exists:
            # Same columns as your real table, but no rows are copied.
            # The id column gets its own counter so the real table's
            # id sequence is not used.
            conn.execute("CREATE TABLE verification_records "
                         "(LIKE public.verification_records INCLUDING DEFAULTS INCLUDING CONSTRAINTS)")
            conn.execute("ALTER TABLE verification_records ALTER COLUMN id DROP DEFAULT")
            conn.execute("ALTER TABLE verification_records "
                         "ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY")
        else:
            conn.execute("""
                CREATE TABLE verification_records (
                    id SERIAL PRIMARY KEY, package_name TEXT, package_version TEXT,
                    ecosystem TEXT, file_name TEXT, sha256 TEXT, sha512 TEXT,
                    hash_status TEXT, signature_status TEXT, source_status TEXT,
                    version_status TEXT, attestation_status TEXT, overall_status TEXT
                )
            """)
    create_tables(factory)

    yield factory

    with get_connection() as conn:
        conn.execute(f"DROP SCHEMA {schema} CASCADE")


