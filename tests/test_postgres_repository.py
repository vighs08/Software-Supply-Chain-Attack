def test_detection_alert_email_and_duplicate_in_postgres(repo, detector):
    from alerts.alert_service import AlertService
    from alerts.email_notifier import EmailSettings

    service = AlertService(repo, EmailSettings(enabled=False))
    sample = _load("suspicious_maintainer_takeover.json")

    first = service.process_detection(detector.analyze(sample))
    second = service.process_detection(detector.analyze(sample))

    assert first["alert_action"] == "CREATED"
    assert second["alert_action"] == "DUPLICATE_SUPPRESSED"

    alert = repo.get_alert(first["alert"]["id"])
    assert alert["severity"] == "Critical"
    assert alert["occurrence_count"] == 2
    assert alert["email_status"] == "DISABLED"
    assert alert["reasons"][0]["code"]          # JSONB round-trip
    assert alert["detection_id"] == first["detection_id"]


def test_triage_in_postgres(repo, detector):
    from alerts.alert_service import AlertService
    from alerts.email_notifier import EmailSettings
    from alerts.triage import change_status

    service = AlertService(repo, EmailSettings(enabled=False))
    alert_id = service.process_detection(
        detector.analyze(_load("suspicious_credential_stealer.json"))
    )["alert"]["id"]

    change_status(repo, alert_id, "Under Review", analyst="tester")
    alert = change_status(repo, alert_id, "Resolved", action_taken="Rotated keys", notes="done")

    assert alert["status"] == "RESOLVED"
    assert alert["closed_at"] is not None
    assert [h["new_status"] for h in alert["history"]] == ["UNDER_REVIEW", "RESOLVED"]
    assert repo.list_alerts(needs_attention=True) == []
    assert repo.summary()["by_status"] == {"RESOLVED": 1}

    # Concurrent-change protection: old status no longer matches.
    assert repo.update_status(alert_id, "NEW", "UNDER_REVIEW", None, None, None) is False


