def test_latest_verification_lookup(repo, pg_factory):
    with pg_factory() as conn:
        conn.execute(
            "INSERT INTO verification_records (package_name, package_version, hash_status, overall_status) "
            "VALUES ('pkg', '1.0', 'PASS', 'VERIFIED'), ('pkg', '1.0', 'FAIL', 'NOT_VERIFIED')"
        )
    row = repo.get_latest_verification("pkg", "1.0")
    assert row["hash_status"] == "FAIL"
    assert repo.get_latest_verification("pkg", "9.9") is None


def test_existing_save_audit_record_in_test_schema(pg_factory, monkeypatch):
    """The EXISTING save_audit_record() writes and the row can be read back."""

    import database.audit_logger as audit_logger
    from database.alert_repository import PostgresAlertRepository

    monkeypatch.setattr(audit_logger, "get_connection", pg_factory)
    record = {
        "package_name": "ssca-test-audit", "package_version": "0.0.1", "ecosystem": "python",
        "file_name": "test_package.txt", "sha256": "a" * 64, "sha512": "b" * 128,
        "hash_status": "PASS", "signature_status": "NOT_CHECKED", "source_status": "TRUSTED",
        "version_status": "PASS", "attestation_status": "PASS", "overall_status": "NOT_VERIFIED",
    }

    record_id = audit_logger.save_audit_record(record)
    row = PostgresAlertRepository(pg_factory).get_latest_verification("ssca-test-audit", "0.0.1")

    assert row["id"] == record_id
    for key, value in record.items():
        assert row[key] == value


def test_verify_then_analyze_through_api(repo, pg_factory, detector, monkeypatch):
    """
    Full flow with the real Flask app and PostgreSQL (test schema):
    POST /verify saves an audit record -> POST /anomaly/analyze picks it up
    automatically -> alert stored -> triage via PATCH.
    """

    import database.audit_logger as audit_logger
    from alerts.alert_service import AlertService
    from alerts.email_notifier import EmailSettings
    from api import app

    project_root = Path(__file__).resolve().parent.parent
    monkeypatch.chdir(project_root)    # verify_package() uses relative paths
    monkeypatch.setattr(audit_logger, "get_connection", pg_factory)

    # `repo` (fixture) starts with empty alert tables in the test schema.
    app.config.update(
        TESTING=True, ALERT_REPOSITORY=repo, ANOMALY_DETECTOR=detector,
        ALERT_SERVICE=AlertService(repo, EmailSettings(enabled=False)),
    )
    try:
        client = app.test_client()

        verify = client.post("/verify", json={
            "package": "test-package", "version": "1.0.0", "file": "test_package.txt",
        })
        assert verify.status_code == 200, verify.get_json()
        audit_id = verify.get_json()["audit_record_id"]

        observation = _load("suspicious_credential_stealer.json")
        observation.update(package_name="test-package", version="1.0.0")
        del observation["integrity"]

        body = client.post("/anomaly/analyze", json=observation).get_json()
        assert body["detection"]["integrity"]["source"] == f"verification_records#{audit_id}"
        assert body["detection"]["integrity"]["statuses"]["hash"] == "PASS"
        alert_id = body["response"]["alert"]["id"]

        patched = client.patch(f"/alerts/{alert_id}/status", json={
            "status": "False Positive", "action_taken": "Automated test", "analyst": "pytest",
        }).get_json()
        assert patched["status"] == "FALSE_POSITIVE"
        assert client.get("/alerts/summary").get_json()["by_status"] == {"FALSE_POSITIVE": 1}
    finally:
        for key in ("ALERT_REPOSITORY", "ANOMALY_DETECTOR", "ALERT_SERVICE"):
            app.config.pop(key, None)
